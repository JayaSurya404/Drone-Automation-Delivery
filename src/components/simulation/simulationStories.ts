// Helper to generate dynamic multi-drone fleet configurations for 5, 10, 25, 50 drones
export const generateMultiDroneFleet = (count: number = 5): MultiDroneSimState[] => {
  const colors = ['#06b6d4', '#10b981', '#f59e0b', '#3b82f6', '#a855f7', '#ec4899', '#14b8a6', '#6366f1'];
  const fleet: MultiDroneSimState[] = [];

  for (let i = 1; i <= count; i++) {
    const idNum = i < 10 ? `0${i}` : `${i}`;
    const id = `D-${idNum}`;
    const color = colors[(i - 1) % colors.length];
    const angle = (i / count) * Math.PI * 2;
    const radius = 25 + (i % 3) * 5;

    const startX = Math.cos(angle) * radius;
    const startZ = Math.sin(angle) * radius;
    const targetX = -startX;
    const targetZ = -startZ;

    const altitude = 60 + (i % 4) * 20; // 60m, 80m, 100m, 120m
    const speed = 38 + (i % 5) * 3;
    const battery = 75 + ((i * 7) % 22);

    fleet.push({
      id,
      name: `SkyNav Airway Unit ${i}`,
      missionId: `MIS-10${300 + i}`,
      color,
      startPos: new THREE.Vector3(startX, 0.2, startZ),
      targetPos: new THREE.Vector3(targetX, 0.2, targetZ),
      currentPos: new THREE.Vector3(startX * 0.4, altitude * 0.2, startZ * 0.4),
      altitude,
      speed,
      battery,
      status: i % 4 === 0 ? 'Returning' : 'In Flight',
      progress: (i * 0.17) % 1.0,
    });
  }

  return fleet;
};

export const MULTI_DRONE_FLEET: MultiDroneSimState[] = generateMultiDroneFleet(5);
