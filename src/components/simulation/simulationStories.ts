import * as THREE from 'three';

export interface StoryScene {
  id: number;
  sceneNumber: string; // e.g. "PHASE 01"
  title: string;
  badge: string;
  shortDesc: string;
  explanation: string;
  duration: number; // in seconds
  cameraMode: 'operations' | 'follow' | 'fpv' | 'top' | 'customer' | 'obstacle' | 'hub';
  flightPhase: 'idle' | 'preflight' | 'takeoff' | 'climb' | 'cruise' | 'hover' | 'descent' | 'landing' | 'delivered' | 'return' | 'completed';
  status: 'normal' | 'warning' | 'critical' | 'delivery' | 'return';
  dronePos: THREE.Vector3;
  droneRot: THREE.Euler;
  altitude: number; // in meters
  speed: number; // in km/h
  heading: number; // in degrees
  battery: number; // in %
  temperature: number; // in °C
  signalRssi: number; // in -dBm
  distanceTraveledKm: number;
  etaMinutes: number;
  payloadAttached: boolean;
  obstacleScanning: boolean;
  isObstaclePresent: boolean;
  isRerouted: boolean;
  decisionAlert?: {
    type: 'info' | 'warning' | 'reroute' | 'emergency';
    title: string;
    details: string;
    reason: string;
  };
  eventLog: string;
}

